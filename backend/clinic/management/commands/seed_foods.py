class Command(BaseCommand):
    help = "Seeds the food picker with a starter catalog of common Iraqi foods across all 10 categories."

    def handle(self, *args, **options):
        created, skipped = 0, 0
        for name, category, unit, cal, protein, carbs, fat in FOODS:
            _, was_created = Food.objects.get_or_create(
                name=name,
                defaults={
                    "category": category, "unit": unit,
                    "calories_per_unit": cal, "protein_per_unit": protein,
                    "carbs_per_unit": carbs, "fat_per_unit": fat,
                },
            )
            created += was_created
            skipped += not was_created
        self.stdout.write(self.style.SUCCESS(
            f"الأصناف الغذائية: {created} جديد من أصل {len(FOODS)} — {skipped} موجود مسبقاً"
        ))
